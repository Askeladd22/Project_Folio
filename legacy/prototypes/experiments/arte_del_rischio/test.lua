local R = require('experiments.arte_del_rischio.rules')
assert(R.score(1,{1,1,1,1})==7)
assert(R.score(1,{1,1,2,3})==3)
assert(R.score(2,{4,4,3,4})==8)
assert(R.score(3,{1,2,3,6})==10)
assert(R.score(3,{1,2,3,5})==0)
local s=R.new('A'); assert(not R.start(s,15)); assert(R.select(s,1))
assert(R.start(s,15)); assert(not R.select(s,2)); assert(not R.bank(s))
assert(R.settle(s,{1,1,2,3})); assert(not R.select(s,2))
assert(R.start(s,12)); assert(R.settle(s,{[3]=2,[4]=3}))
assert(s.phase=='ended' and s.score==0 and s.last=='Rischio fallito')
assert(R.next_turn(s)); assert(s.turn==2 and s.rerolls==2)
local c=R.new('C'); assert(R.select(c,3)); assert(R.start(c,15))
assert(R.settle(c,{1,1,4,4})); assert(R.select(c,1)); assert(not R.select(c,2))
assert(R.bank(c)); assert(c.score==1 and #c.works==1)
local b=R.new('B'); assert(not R.select(b,1)); assert(R.start(b,15))
assert(R.settle(b,{1,1,2,3})); assert(R.select(b,1)); assert(not R.select(b,2))
assert(R.bank(b) and b.score==3)
local t=R.new('A'); R.select(t,3); R.start(t,15); R.settle(t,{5,5,5,5})
for i=1,2 do assert(R.start(t,1)); assert(R.settle(t,{[1]=5})) end
assert(not R.start(t,1)); assert(R.start(t,1,true)); assert(t.score==-1 and t.temptations==1)
assert(R.settle(t,{[1]=5})); assert(not R.start(t,1,true)); assert(R.abandon(t))
assert(R.next_turn(t)); R.select(t,3); R.start(t,15); R.settle(t,{5,5,5,5})
for i=1,2 do R.start(t,1); R.settle(t,{[1]=5}) end
assert(R.start(t,1,true) and t.score==-3)
assert(not R.settle(t,{[1]=7})); assert(t.phase=='rolling')
assert(R.settle(t,{[1]=1})); assert(t.hand[2]==5)
assert(R.abandon(t)); while t.turn<8 do R.next_turn(t); R.abandon(t) end
assert(t.finished and not R.next_turn(t))
print('risk rules: recipes, A/B/C, risk loss, penalties, partial callbacks, bounds PASS')
local win=R.new('A'); win.turn=8; win.score=15; win.counts={1,1,0}
assert(R.select(win,3)); assert(R.start(win,15)); assert(R.settle(win,{1,2,3,6}))
assert(R.bank(win) and win.finished and win.won and win.score==25)
local max=R.new('A'); R.select(max,3); R.start(max,15); R.settle(max,{1,2,3,6})
R.start(max,1); R.settle(max,{[1]=1}); assert(max.phase=='ended')
assert(not R.select(max,1) and not R.bank(max))
local good=R.new('C'); R.select(good,1); R.start(good,15); R.settle(good,{1,1,2,3})
R.start(good,4); R.settle(good,{[3]=1}); assert(good.phase=='ready' and R.reward(good)==5)
assert(R.bank(good) and good.score==5)
print('risk rules: victory, maximum recipe certainty of bust, successful risky improvement PASS')
local RNG=require('experiments.arte_del_rischio.rng')
