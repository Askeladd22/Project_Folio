require('core')
local P=require('src.engine3d.physics')
local C=require('src.core.dice_config').load()
assert(C.scene.box.gravity==25,'gravity must be explicit')
assert(C.scene.box.restitution==.25,'restitution must preserve actual runtime')
assert(C.scene.box.friction==.75,'friction must mean friction')
assert(C.scene.box.fixed_dt==.01,'fixed_dt must be explicit')
local b=clone(P.box,{timeleft=0}):configure(C.scene.box)
assert(b.x==9.2 and b.y==3.8 and b.z==10)
assert(b.gravity==25 and b.bounce==.25 and b.friction==.75 and b.dt==.01)
assert(b.linear_damping==.12 and b.angular_damping==.12 and b.border_height==.74)
assert(not pcall(function() b:configure({half_x=1,half_y=1,height=1,gravity=25,restitution=.3,friction=.8,fixed_dt=0}) end),'reject zero timestep')
print('PASS expanded tray schema to physical world, dynamics preserved')
