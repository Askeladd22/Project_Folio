local T=require('src.features.farkle.mouse_throw')
local view={yaw=0,pitch=.48,focus=5,distance=14.1}
assert(T.begin(0,10,20,1)==nil,'invalid die index accepted')
assert(T.begin(1,0/0,20,1)==nil,'NaN gesture accepted')
local click=T.begin(2,100,120,1)
assert(T.finish(click,112,124,1.3,view,20)==nil,'small right click must never roll')
local held=T.begin(3,100,200,1)
assert(T.move(held,200,160,1.15))
local pose=T.preview(held,view,20)
assert(pose.index==3 and pose.z>.35 and pose.x>0 and pose.y<0)
assert(not T.preview(nil,view,20))
local dir=T.finish(held,200,160,1.16,view,20)
assert(dir and dir.x>0 and dir.y<0,'mouse throw must follow drag in world coordinates')
assert(dir.power>=.35 and dir.power<=1.45,'gesture power out of bounds')
assert(math.abs(math.sqrt(dir.x^2+dir.y^2)-1)<1e-9,'launch direction not normalized')
local slow=T.begin(1,0,0,0)
local slow_aim=T.finish(slow,30,0,10,view,20)
assert(slow_aim and slow_aim.power==.35,'very slow swipe not safely clamped')
local fast=T.begin(1,0,0,0)
local fast_aim=T.finish(fast,300,0,.001,view,20)
assert(fast_aim and fast_aim.power==1.45,'fast swipe must be bounded')
local yawed={yaw=math.pi/2,pitch=.48,focus=5,distance=14.1}
local wx,wy=T.world_motion(100,0,yawed,20)
assert(math.abs(wx)<1e-8 and wy<0,'screen vector must respect tray camera yaw')
local a=T.preview({index=1,x0=0,y0=0,x=9000,y=0,t0=0,t=1},view,20)
assert(a.x<100 and a.z<=1.2,'drag preview should stay bounded')
