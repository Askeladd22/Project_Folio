 local f=assert(io.open(path,'rb'));local s=f:read('*a');f:close();return s
end
local controller=read('src/features/farkle/controller.lua')
assert(controller:find('if b==2 then',1,true),'right mouse grab not hooked')
assert(controller:find('Bridge.pickTrayDie(x,y)',1,true),'throw must begin from a real die')
assert(controller:find('R.can_roll(self.game)',1,true),'Farkle legal throw gate missing')
assert(controller:find('if b~=1 or self.state',1,true),'left click selection must remain')
assert(controller:find('self:request(false,launch)',1,true),'mouse must start a normal Farkle request')
local runtime=read('src/app/dice_runtime.lua')
assert(runtime:find('not recovery and not technical',1,true),'physical retry must not reuse mouse aim')
assert(runtime:find('drag_preview=MouseThrow.preview',1,true),'GPU hand preview missing')
local live=read('src/engine3d/g3d_live.lua')
assert(live:find('args.drag_preview',1,true),'GPU must consume render-only drag pose')
assert(not package.loaded['lib.g3d'],'pure gesture tests must not initialize graphics')
print('PASS mouse grab throw: right-click gate, camera-aligned direction, bounded impulse, preview and retry isolation')
