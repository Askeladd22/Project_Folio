local R=require('src.gameplay.farkle.rules')
local P=require('src.features.farkle.presentation')
local s=R.new();local p=P.new(s)
local function observe() return P.observe(p,s,{},false) end
assert(R.start(s));observe();assert(R.settle(s,{1,5,3,3,3,6}));P.accepted(p,s.active);observe()
R.toggle(s,1);R.toggle(s,2)
local pending=P.prepare(p,s);assert(R.take(s));P.commit(p,s,pending,'take',false);observe()
assert(p.score.to==15 and p.score.from==0 and #p.ledger==2)
assert(P.display(p,'pot',s.pot)==0);P.update(p,.4,false)
assert(P.display(p,'pot',s.pot)>0 and P.display(p,'pot',s.pot)<15)
P.finish(p);assert(P.display(p,'pot',s.pot)==15 and s.pot==15)
for i=3,5 do R.toggle(s,i) end
pending=P.prepare(p,s);assert(R.bank_turn(s));P.commit(p,s,pending,'bank',false);observe()
assert(p.score.to==45 and p.score.channel=='bank' and #p.ledger==3)
P.update(p,1,false);assert(P.display(p,'bank',s.bank)==45 and s.bank==45)
assert(observe()==nil,'observation does not replay events')
assert(R.next_turn(s));observe();assert(#p.ledger==0 and not p.score)
s=R.new();p=P.new(s);assert(R.equip_reference(s,'bank_multiplier_gold'))
assert(R.start(s));observe();assert(R.settle(s,{1,5,2,3,4,6}));observe();R.toggle(s,1)
pending=P.prepare(p,s);assert(R.use_reference(s));P.commit(p,s,pending,'medal',true);observe()
assert(s.bank==20 and p.bonus==10 and p.score.base==10 and p.score.to==20)
assert(P.display(p,'bank',s.bank)==20 and s.medalCharges==0)
P.finish(p);assert(s.bank==20 and s.medalCharges==0)
assert(P.transfer_duration>=.4 and P.transfer_duration<=.7)
assert(P.score_duration>=.5 and P.score_duration<=.9)
print('PASS presentation ledger, bank/medal separation, skip, reduced, real totals and no double consumption')
