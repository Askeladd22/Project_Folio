-- EX-BG-001 deterministic headless regression, Lua 5.4 and LuaJIT.
local E=require('experiments.battute_gemelle_lab.engine')
local S=require('experiments.battute_gemelle_lab.simulate')
local Rules=require('src.farkle.rules')
local n=0
local function check(label,fn)
  fn();n=n+1;print('PASS BG '..label)
end
local function choose(s,points)
  local a=s.actors[s.active]
  for _,o in ipairs(Rules.options(a.turn)) do
    if o.points==points then return assert(E.take(s,o.mask)) end
  end
  error('missing option for '..tostring(points))
end
local low={1,2,3,4,6,2}
local bust={2,2,3,3,4,6}
check('canonical scoring, no duplicated point table',function()
  assert(Rules.points.single[1]==10 and Rules.points.single[5]==5)
  assert(Rules.points.kind[3][1]==75)
  assert(Rules.points.kind[6][6]==750)
  assert(Rules.score({1,1,1})==75)
end)
check('one leader roll grants exactly one follower roll; ties to leader',function()
  local s=E.new(101,'player')
  assert(not E.bank(s) and not E.take(s,1))
  assert(E.roll(s,low))
  assert(choose(s,10))
  assert(E.bank(s))
  assert(s.limit==1 and s.target==10 and s.active=='rival')
  assert(E.roll(s,low))
  assert(choose(s,10))
  assert(s.phase=='hand_end')
  assert(s.history[1].reason=='tie' and s.history[1].winner=='player')
  assert(s.history[1].follower_rolls==1)
  assert(not E.roll(s) and not E.bank(s))
end)
check('follower beats public target and stops without extra rolls',function()
  local s=E.new(102,'player')
  assert(E.roll(s,low) and choose(s,10) and E.bank(s))
  assert(E.roll(s,{1,1,1,2,3,4}))
  assert(choose(s,75))
  assert(s.history[1].winner=='rival' and s.history[1].reason=='exceeded')
  assert(s.history[1].follower_rolls==1)
end)
check('leader Farkle loses immediately, follower does not roll',function()
  local s=E.new(103,'player')
  assert(E.roll(s,bust))
  assert(s.phase=='hand_end' and s.history[1].winner=='rival')
  assert(s.history[1].reason=='farkle')
  assert(s.history[1].follower_rolls==0)
end)
check('follower Farkle loses immediately',function()
  local s=E.new(104,'player')
  assert(E.roll(s,low) and choose(s,10) and E.bank(s))
  assert(E.roll(s,bust))
  assert(s.history[1].winner=='player')
  assert(s.history[1].reason=='farkle')
end)
check('hot dice uses the canonical reset of all six physical IDs',function()
  local s=E.new(105,'player')
  assert(E.roll(s,{1,1,1,5,5,5}))
  local full
  for _,o in ipairs(Rules.options(s.actors.player.turn)) do
    if o.mask==63 then full=o end
  end
  assert(full and full.points==250)
  assert(E.take(s,63))
  assert(s.actors.player.turn.hot and s.metrics.hot==1)
  assert(E.roll(s,{1,2,3,4,5,6}))
  assert(#s.actors.player.turn.active==6)
  assert(s.actors.player.rolls==2)
end)
check('third leader roll forces bank; follower never exceeds k',function()
  local s=E.new(106,'player')
  assert(E.roll(s,low) and choose(s,10))
  assert(E.roll(s,{[2]=1,[3]=2,[4]=3,[5]=4,[6]=6}) and choose(s,10))
  assert(E.roll(s,{[3]=1,[4]=2,[5]=3,[6]=4}) and choose(s,10))
  assert(s.active=='rival' and s.limit==3 and s.target==30)
  assert(s.actors.player.rolls==3)
  assert(not E.bank(s))
end)
check('invalid masks, invalid bank and duplicate selection do not advance',function()
  local s=E.new(107,'player')
  assert(not E.take(s,0))
  assert(E.roll(s,low))
  assert(not E.take(s,63))
  assert(not E.take(s,-1))
  assert(not E.bank(s))
  assert(choose(s,10))
  assert(not E.take(s,1))
  assert(E.bank(s))
  assert(not E.next_hand(s))
end)
check('roles alternate, best of three and bounded hands',function()
  local s=E.new(108,'player')
  assert(E.roll(s,bust))
  assert(s.wins.rival==1 and s.phase=='hand_end')
  assert(E.next_hand(s))
  assert(s.hand==2 and s.leader=='rival')
  assert(E.roll(s,bust))
  assert(s.wins.player==1 and s.phase=='hand_end')
  assert(E.next_hand(s))
  assert(s.hand==3 and s.leader=='player')
  assert(E.roll(s,bust))
  assert(s.phase=='finished' and s.winner=='rival')
  assert(#s.history==3 and not E.next_hand(s))
end)
check('same seed and policies reproduce full match events',function()
  for seed=101,120 do
    local a=S.play(seed,'informed','aggressive')
    local b=S.play(seed,'informed','aggressive')
    assert(a.winner==b.winner and #a.history==#b.history)
    assert(#a.events==#b.events)
    for i=1,#a.events do
      local x,y=a.events[i],b.events[i]
      assert(x.hand==y.hand and x.kind==y.kind and
        x.side==y.side and x.detail==y.detail)
    end
  end
end)
check('policy pilot and counterfactual estimate are reproducible',function()
  local a=S.pilot(5,501)
  local b=S.pilot(5,501)
  assert(a==b and a:find('paired delta',1,true))
  local s=E.new(509,'player')
  if s.phase=='turn' and E.roll(s) and s.phase=='turn' then
    local o=assert(Rules.options(s.actors.player.turn)[1])
    assert(E.take(s,o.mask))
    local x,y=S.estimate(s.actors.player.turn,1,'prudent',8,700)
    local z,w=S.estimate(s.actors.player.turn,1,'prudent',8,700)
    assert(x==z and y==w and x>=0 and x<=1 and y>=0 and y<=1)
  end
  assert(S.diagnostic(3,8):find('decisive action flips',1,true))
end)
print('PASS Battute Gemelle: '..n..' cases')
